const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
assert.ok(fs.existsSync(path.join(__dirname,'../workflow-model.js')),'Persistent workflow model must exist');
const W=require('../workflow-model.js');
const data={root:[{id:'same',title:'Root',dueDate:'2026-11-15',priorityDate:'2026-11-02',priorityOrder:0},{id:'b',priorityDate:'2026-11-03',priorityLevel:'other',priorityOrder:0}],project:[{id:'same',projectId:'case',title:'Case task',dueDate:'2026-11-20',priorityDate:'2026-11-03',priorityLevel:'other',priorityOrder:1}]};
const moved=W.movePriority(data,{id:'same',scope:'root'},{date:'2026-11-03',level:'other',before:{id:'same',scope:'project'}},'2026-10-31T20:00:00Z');
assert.equal(moved.root[0].dueDate,'2026-11-15');
assert.equal(moved.root[0].priorityDate,'2026-11-03');
assert.equal(moved.project[0].dueDate,'2026-11-20');
const roundtrip=JSON.parse(JSON.stringify(moved));
const entries=Object.entries(roundtrip).flatMap(([scope,items])=>items.map(task=>({scope,task})));
assert.deepEqual(W.ordered(entries).map(e=>e.scope+':'+e.task.id),['root:b','root:same','project:same']);
assert.equal(data.root[0].priorityDate,'2026-11-02','model never mutates input');
assert.equal(W.movePriority(data,{id:'missing',scope:'root'},{date:'2026-11-03',level:'main'}),null);
assert.equal(W.movePriority(data,{id:'same',scope:'root'},{date:'2026-02-31',level:'main'}),null);
assert.equal(W.movePriority(data,{id:'same',scope:'root'},{date:'2026-11-03',level:'bad'}),null);
let done={root:[{id:'x',status:'done'}],project:[]};
assert.equal(W.movePriority(done,{id:'x',scope:'root'},{date:'2026-11-03',level:'main'}),null);
let p={draftHtml:'<p>First</p>'};
let patch=W.draftPatch(p,'<p>Second</p>','2026-10-31T20:00:00Z');
assert.equal(patch.draftHistory[0].html,'<p>First</p>');
p={...p,...patch};
assert.equal(W.draftPatch(p,p.draftHtml,'2026-10-31T20:00:01Z'),null,'unchanged saves create no version');
for(let i=0;i<14;i++)p={...p,...W.draftPatch(p,'Revision '+i,'2026-10-31T20:00:02Z')};
assert.equal(p.draftHistory.length,10);
assert.equal(new Set(p.draftHistory.map(x=>x.id)).size,10);
const chosen=p.draftHistory[0].html,current=p.draftHtml;
p={...p,...W.draftPatch(p,chosen,'2026-10-31T20:01:00Z')};
assert.equal(p.draftHtml,chosen);assert.equal(p.draftHistory[0].html,current,'restore keeps current text recoverable');
assert.equal(W.draftPatch({draftHtml:''},'New','x').draftHistory.length,0);
let disk=structuredClone(data), writes=0;
assert.equal(typeof W.commitCollections,'function','priority writes need rollback');
assert.equal(W.commitCollections(data,moved,(scope,value)=>{writes++;if(writes===2)return false;disk[scope]=structuredClone(value);return true;}),false);
assert.deepEqual(disk,data,'failed second write rolls back the first collection');
console.log('PASS workflow: scope-safe persistent order, unchanged deadlines, validation, bounded recoverable revisions');
