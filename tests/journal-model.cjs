const assert=require('node:assert/strict');
const W=require('../workflow-model.js');
assert.equal(typeof W.monthDays,'function','calendar model must exist');
const nov=W.monthDays(2026,10);
assert.equal(nov.length,42);assert.equal(nov[6],'2026-11-01');assert.equal(nov[35],'2026-11-30');
assert.equal(nov.filter(Boolean).length,30);
assert.equal(W.monthDays(2024,1).filter(Boolean).length,29);
assert.equal(W.monthDays(2025,1).filter(Boolean).length,28);
assert.equal(W.monthDays(2026,11).filter(Boolean).at(-1),'2026-12-31');
const original={id:'root',title:'Parent',custom:{retain:true},dueDate:'2026-11-20',subtasks:[]};
const added=W.patchSubtask(original,{type:'add',id:'s1',title:'  Проверить практику  '},'t1');
assert.equal(added.subtasks[0].title,'Проверить практику');assert.equal(original.subtasks.length,0);
assert.deepEqual(added.custom,{retain:true});assert.equal(added.dueDate,original.dueDate);
assert.deepEqual(W.subtaskProgress(added),{done:0,total:1});
const done=W.patchSubtask(added,{type:'toggle',id:'s1'},'t2');
assert.deepEqual(W.subtaskProgress(done),{done:1,total:1});assert.equal(done.status,undefined,'children never auto-complete parent');
const edited=W.patchSubtask(done,{type:'edit',id:'s1',title:'Новое название'},'t3');
assert.equal(edited.subtasks[0].completed,true);assert.equal(edited.subtasks[0].title,'Новое название');
assert.equal(W.patchSubtask(edited,{type:'add',id:'s2',title:' '},'t4'),null);
assert.equal(W.patchSubtask(edited,{type:'add',id:'s1',title:'Duplicate'},'t4'),null);
assert.equal(W.patchSubtask(edited,{type:'toggle',id:'missing'},'t4'),null);
assert.deepEqual(W.patchSubtask(edited,{type:'remove',id:'s1'},'t4').subtasks,[]);
assert.deepEqual(W.subtaskProgress({}),{done:0,total:0});
console.log('PASS journal model: calendar geometry, leap years, immutable validated subtasks and parent/legacy-field retention');
