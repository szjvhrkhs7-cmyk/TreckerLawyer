/* Generate a deterministic, integrity-checked release package. Run after embed-page-assets. */
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..'),read=name=>fs.readFileSync(path.join(root,name));
const html=read('index.html').toString(),sync=read('sync.js').toString(),manifest=JSON.parse(read('manifest.webmanifest'));
const names=new Set(['index.html','manifest.webmanifest','app-icon.svg']);
for(const match of html.matchAll(/<script\b[^>]*\bsrc="([^"]+)"/g))names.add(match[1].split('?')[0]);
for(const match of sync.matchAll(/loadScript\('([^']+)'/g))names.add(match[1].split('?')[0]);
for(const match of html.matchAll(/<link\b[^>]*\bhref="([^"]+\.png)[^"]*"/g))names.add(match[1]);
for(const icon of manifest.icons)names.add(icon.src.split('?')[0]);
const hash=crypto.createHash('sha256');
hash.update(fs.readFileSync(__filename)); // Worker-only changes must never share an active cache.
const assets=[...names].sort().map(name=>{if(name.includes('..')||/^https?:/.test(name))throw Error('Offline assets must be local');const data=read(name);hash.update(name);hash.update(data);return{path:name,integrity:'sha256-'+crypto.createHash('sha256').update(data).digest('base64')};});
const release=hash.digest('hex').slice(0,20);
const worker=`/* Generated by scripts/build-offline-worker.cjs; cache contains only public app files. */
'use strict';
const RELEASE = '${release}';
const ASSETS = ${JSON.stringify(assets,null,2)};
const BASE = new URL(self.registration.scope);
const PREFIX = 'lawyer-shell:' + BASE.pathname + ':';
const CACHE = PREFIX + RELEASE;
const urls = ASSETS.map(asset => new URL(asset.path, BASE).href);
const allowed = new Set(urls.map(url => new URL(url).pathname));
const shell = new URL('index.html', BASE).href;
self.addEventListener('install', event => event.waitUntil((async () => {
  try {
    const cache = await caches.open(CACHE);
    await cache.addAll(ASSETS.map(asset => new Request(new URL(asset.path, BASE).href, {cache:'reload', integrity:asset.integrity})));
    if (!self.registration.active) await self.skipWaiting();
  } catch (error) { await caches.delete(CACHE); throw error; }
})()));
self.addEventListener('activate', event => event.waitUntil((async () => {
  for (const name of await caches.keys()) if (name.startsWith(PREFIX) && name !== CACHE) await caches.delete(name);
  await self.clients.claim();
})()));
self.addEventListener('fetch', event => {
  const request = event.request, url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== BASE.origin) return;
  const navigation = request.mode === 'navigate' && (url.pathname === BASE.pathname || url.pathname === new URL(shell).pathname);
  if (!navigation && !allowed.has(url.pathname)) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const response = await cache.match(navigation ? shell : new URL(url.pathname, BASE.origin).href);
    // A missing cache entry is never replaced with unrelated HTML or an auth response.
    return response || fetch(request);
  })());
});
self.addEventListener('message', event => {
  if (event.data?.type === 'ACTIVATE_UPDATE') event.waitUntil(self.skipWaiting());
  if (event.data?.type === 'CHECK_READY' || event.data?.type === 'PREPARE_CACHE') event.waitUntil((async () => {
    let complete = false;
    try {
      const cache = await caches.open(CACHE);
      if (event.data.type === 'PREPARE_CACHE') await cache.addAll(ASSETS.map(asset => new Request(new URL(asset.path, BASE).href, {cache:'reload', integrity:asset.integrity})));
      complete = (await Promise.all(urls.map(url => cache.match(url)))).every(Boolean);
    } catch {} // Keep any still usable cached files when repair fails.
    event.ports?.[0]?.postMessage({type:complete?'READY':'NOT_READY', release:RELEASE});
  })());
});
`;
fs.writeFileSync(path.join(root,'sw.js'),worker);
console.log(`Offline release ${release}: ${assets.length} integrity-checked local assets`);
